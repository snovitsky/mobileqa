export function userError(code) {
 const known = Object.hasOwn(ERROR_MESSAGES, code) ? code : 'operationFailed';
 const error = new Error(ERROR_MESSAGES[known]);
 error.code = known;
 return error;
}

export function userMessage(error, fallbackCode = 'operationFailed') {
 const code = error?.code;
 if (Object.hasOwn(ERROR_MESSAGES, code)) return ERROR_MESSAGES[code];
 return ERROR_MESSAGES[Object.hasOwn(ERROR_MESSAGES, fallbackCode) ? fallbackCode : 'operationFailed'];
}


export function httpStatusMessage(status) {
 const code = Number(status);
 if (!Number.isInteger(code) || code < 100 || code > 599) return 'Браузер не сообщил код ответа страницы. Это само по себе не означает ошибку сайта.';
 if (code === 404) return 'HTTP 404 — страница не найдена. Проверьте адрес или откройте другую страницу сайта.';
 if (code === 401) return 'HTTP 401 — сайт требует входа. Откройте его в обычной вкладке и войдите в свой аккаунт.';
 if (code === 403) return 'HTTP 403 — сайт отказал в доступе. Проверьте, открывается ли страница в обычной вкладке.';
 if (code >= 500) return `HTTP ${code} — сайт сообщил об ошибке сервера. Повторите попытку позже или сообщите владельцу сайта.`;
 if (code >= 400) return `HTTP ${code} — сайт не смог выполнить запрос. Проверьте адрес и откройте страницу в обычной вкладке.`;
 if (code >= 300) return `HTTP ${code} — сайт сообщил о перенаправлении на другую страницу.`;
 if (code >= 200) return `HTTP ${code} — сайт ответил на запрос. Содержимое страницы проверьте в экране.`;
 return `HTTP ${code} — промежуточный ответ сайта. Дождитесь завершения загрузки.`;
}
